#!/usr/bin/env python3
"""Generate the crate list for the BitBake recipe from Cargo.lock (same shape as
`bitbake -c update_crates` writes). `--check` exits 1 if the committed file is stale.

    python scripts/gen_yocto_crates.py [--check]
"""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
lock = (root / "Cargo.lock").read_text()
out_path = root / "yocto/meta-lorawan-gateway-health/recipes-lora/lgh-exporter/lgh-exporter-crates.inc"

crates = []
for block in lock.split("[[package]]")[1:]:
    name = re.search(r'^name = "(.+)"', block, re.M).group(1)
    version = re.search(r'^version = "(.+)"', block, re.M).group(1)
    src = re.search(r'^source = "(.+)"', block, re.M)
    sum_ = re.search(r'^checksum = "(.+)"', block, re.M)
    if src and src.group(1).startswith("registry+") and sum_:
        crates.append((name, version, sum_.group(1)))
crates.sort()

lines = ["# Generated by scripts/gen_yocto_crates.py from Cargo.lock; do not edit.", "", "SRC_URI += \" \\"]
lines += [f"    crate://crates.io/{n}/{v} \\" for n, v, _ in crates]
lines += ['"', ""]
lines += [f'SRC_URI[{n}-{v}.sha256sum] = "{s}"' for n, v, s in crates]
text = "\n".join(lines) + "\n"

if "--check" in sys.argv:
    if not out_path.exists() or out_path.read_text() != text:
        print(f"{out_path} is stale: run python scripts/gen_yocto_crates.py", file=sys.stderr)
        sys.exit(1)
    print(f"ok: {len(crates)} crates")
else:
    out_path.write_text(text)
    print(f"wrote {out_path} ({len(crates)} crates)")
